import * as React from "react";
import { Metadata } from "next";
import { notFound } from "next/navigation";
import { createClient } from "@/utils/supabase/server";
import { getTeamByInviteCode } from "@/lib/data/squads";
import { InviteJoinCard } from "@/components/squads/InviteJoinCard";
import Link from "next/link";
import { Terminal, AlertCircle } from "lucide-react";
import { Button } from "@/components/ui/button";

export const metadata: Metadata = {
  title: "Join Squad | Hackline",
  description: "Accept an invitation to join a hackathon squad on Hackline.",
};

export default async function JoinTeamPage(props: {
  params: Promise<{ inviteCode: string }>;
}) {
  const { inviteCode } = await props.params;

  if (!inviteCode) {
    notFound();
  }

  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  const team = await getTeamByInviteCode(inviteCode);

  return (
    <div className="min-h-screen bg-zinc-950 text-white flex flex-col justify-between selection:bg-indigo-500/30">
      {/* Background ambient mesh */}
      <div className="fixed inset-0 pointer-events-none -z-10 overflow-hidden">
        <div className="absolute top-1/4 left-1/2 -translate-x-1/2 -translate-y-1/2 w-[700px] h-[500px] bg-indigo-600/10 rounded-full blur-[140px]" />
        <div className="absolute top-1/3 left-1/3 w-[400px] h-[300px] bg-purple-600/10 rounded-full blur-[120px]" />
      </div>

      {/* Nav Header */}
      <header className="px-6 py-6 max-w-7xl mx-auto w-full flex items-center justify-between border-b border-zinc-900">
        <Link href="/" className="flex items-center gap-2.5 group">
          <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-zinc-900 border border-zinc-800 text-white transition-colors group-hover:border-zinc-750">
            <Terminal className="h-4 w-4" />
          </div>
          <span className="font-bold tracking-tight text-white font-mono text-sm">
            Hackline
          </span>
        </Link>

        {user ? (
          <Link href="/dashboard">
            <Button size="sm" variant="outline" className="rounded-xl text-xs">
              Go to Dashboard
            </Button>
          </Link>
        ) : (
          <div className="flex items-center gap-2">
            <Link href={`/login?redirect=/join/${inviteCode}`}>
              <Button size="sm" variant="ghost" className="rounded-xl text-xs">
                Log In
              </Button>
            </Link>
            <Link href={`/signup?redirect=/join/${inviteCode}`}>
              <Button size="sm" variant="primary" className="rounded-xl text-xs">
                Sign Up
              </Button>
            </Link>
          </div>
        )}
      </header>

      {/* Main Container */}
      <main className="flex-1 flex items-center justify-center p-4 sm:p-6">
        {!team ? (
          <div className="max-w-md w-full rounded-2xl bg-zinc-950 border border-zinc-800 p-8 text-center shadow-2xl">
            <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-rose-500/10 border border-rose-500/20 text-rose-400 mx-auto mb-4">
              <AlertCircle className="h-6 w-6" />
            </div>
            <h2 className="text-base font-bold text-white tracking-tight">
              Squad Invitation Not Found
            </h2>
            <p className="mt-2 text-xs text-zinc-400 leading-relaxed">
              This squad invite link has either expired, been regenerated by the squad captain, or never existed.
            </p>
            <div className="mt-6">
              <Link href="/dashboard">
                <Button variant="primary" className="w-full rounded-xl text-xs">
                  Return to Dashboard
                </Button>
              </Link>
            </div>
          </div>
        ) : (
          <InviteJoinCard
            team={team}
            isAuthenticated={Boolean(user)}
            currentUserId={user?.id}
          />
        )}
      </main>

      {/* Footer */}
      <footer className="py-6 text-center text-xs text-zinc-600 font-mono">
        Hackline Engine &bull; High-Velocity Hackathon Management
      </footer>
    </div>
  );
}
